  /**
   * One titled group of questions.
   *
   * @param \Drupal\Core\StringTranslation\TranslatableMarkup $title
   *   The section heading.
   * @param list<array<string, mixed>> $questions
   *   Questions in this section.
   *
   * @return array<string, mixed>
   *   One section.
   */
  private function section(TranslatableMarkup $title, array $questions): array {
    return [
      'title' => $title,
      'questions' => $questions,
    ];
  }

  /**
   * One question with its answer paragraphs.
   *
   * @param string $id
   *   The fragment used in links to this question.
   * @param \Drupal\Core\StringTranslation\TranslatableMarkup $question
   *   The question.
   * @param list<\Drupal\Core\StringTranslation\TranslatableMarkup> $answers
   *   Answer paragraphs.
   *
   * @return array<string, mixed>
   *   One FAQ item.
   */
  private function question(
    string $id,
    TranslatableMarkup $question,
    array $answers,
  ): array {
    return [
      'id' => $id,
      'question' => $question,
      'answers' => $answers,
    ];
  }

