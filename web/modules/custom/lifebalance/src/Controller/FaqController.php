  /**
   * Frequently asked questions. The page has no personal data.
   *
   * @return array<string, mixed>
   *   A render array.
   */
  public function page(): array {
    $build = [
      'questions' => [
        '#type' => 'container',
        '#attributes' => ['class' => ['lifebalance-faq']],
        '#attached' => [
          'library' => ['lifebalance/faq'],
        ],
      ],
    ];
    foreach ($this->sections() as $index => $section) {
      $build['questions']['h' . $index] = [
        '#type' => 'html_tag',
        '#tag' => 'h2',
        '#value' => $section['title'],
      ];
      foreach ($section['questions'] as $question_index => $item) {
        $answers = [];
        foreach ($item['answers'] as $answer_index => $answer) {
          $answers['p' . $answer_index] = [
            '#type' => 'html_tag',
            '#tag' => 'p',
            '#value' => $answer,
          ];
        }
        $key = 'q' . $index . 'x' . $question_index;
        $build['questions'][$key] = [
          '#type' => 'details',
          '#title' => $item['question'],
          '#open' => FALSE,
          '#attributes' => ['id' => $item['id']],
        ] + $answers;
      }
    }
    $meta = $this->publicMeta->elements('lifebalance.faq');
    if (isset($meta['#attached'])) {
      $build['#attached'] = $meta['#attached'];
    }
    return $build;
  }

